import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import { compileModule } from "svelte/compiler";

const source = readFileSync(new URL("../src/lib/core/incidentModel.ts", import.meta.url), "utf8");
const js = ts.transpile(source, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 });
const { appendBoundedIncident, appendBoundedIncidents, parseIncidents, redactIncidentText, filterIncidents, INCIDENT_LIMIT } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const secrets = ["server-secret", "db-secret", "cfxk_abc123", "hook-secret", "auth-secret", "key-secret"];
const redacted = redactIncidentText('rcon_password "server-secret"\nmysql://root:db-secret@localhost/db\nsv_licenseKey cfxk_abc123\nhttps://discord.com/api/webhooks/hook-secret\nAuthorization: Bearer auth-secret\n-----BEGIN PRIVATE KEY-----\nkey-secret\n-----END PRIVATE KEY-----');
for (const secret of secrets) assert.ok(!redacted.includes(secret), `Leaked ${secret}`);
assert.ok(!redactIncidentText('const api_key = "abc-secret";').includes("abc-secret"));
assert.equal(redactIncidentText("x".repeat(10_000)).length, 2000);
let items = [];
for (let i = 0; i < 1100; i++) items = appendBoundedIncident(items, { id: `event-${i}`, timestamp: 1000 + i, workspaceId: i % 2 ? "qa" : "default", type: "health", title: `CPU threshold ${i}` }, 10_000);
assert.equal(items.length, INCIDENT_LIMIT);
assert.equal(items[0].id, "event-1099");
assert.equal(appendBoundedIncident(items, items[0]).length, INCIDENT_LIMIT);
assert.equal(filterIncidents(items, { workspaceId: "qa", type: "health", after: 2000, search: "threshold" }).length, 50);
assert.equal(filterIncidents(items, { type: "config" }).length, 0);
assert.deepEqual(parseIncidents("not-json"), []);
assert.deepEqual(parseIncidents('{"bad":true}'), []);
const restored = parseIncidents(JSON.stringify([{ id: "fixture", title: "password=hidden", detail: "token=hidden", panel: "javascript:bad", workspaceId: "token=hidden" }]));
assert.equal(restored[0].panel, "logs");
assert.equal(restored[0].workspaceId, "default");
assert.ok(!JSON.stringify(restored).includes("hidden"));
assert.equal(parseIncidents(JSON.stringify(items)).length, INCIDENT_LIMIT);
const burst = Array.from({ length: 5000 }, (_, i) => ({ id: `burst-${i}`, timestamp: 1000 + i, title: `Resource started ${i}` }));
const batched = appendBoundedIncidents([], burst, 10_000);
assert.equal(batched.length, 100);
assert.equal(batched[0].id, "burst-4999");

const modelUrl = `data:text/javascript;base64,${Buffer.from(js).toString("base64")}`;
const storeSource = readFileSync(new URL("../src/lib/core/incidents.svelte.ts", import.meta.url), "utf8").replace('from "./incidentModel"', `from "${modelUrl}"`);
const storeJs = ts.transpile(storeSource, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 });
const compiled = compileModule(storeJs, { filename: "incidents.svelte.js", generate: "client" }).js.code.replace(/(from\s+|import\s+)["'](svelte\/[^"']+)["']/g, (_, prefix, specifier) => `${prefix}${JSON.stringify(import.meta.resolve(specifier))}`);
const storage = new Map();
let writes = 0;
const listeners = new Map();
globalThis.localStorage = { getItem: (key) => storage.get(key) ?? null, setItem: (key, value) => { writes++; storage.set(key, value); } };
globalThis.window = { addEventListener: (name, callback) => listeners.set(name, callback) };
const store = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
store.initializeIncidents();
const baselineWrites = writes;
for (let i = 0; i < 5000; i++) store.appendIncident({ id: `runtime-${i}`, title: "Resource started", detail: "token=private" });
assert.equal(writes, baselineWrites, "Burst wrote to storage synchronously");
await new Promise(queueMicrotask);
assert.equal(store.incidentSession.items.length, 100, "Pending burst must remain bounded");
store.appendIncidents([{ id: "batch-fixture", title: "Config saved", workspaceId: "qa", type: "config" }]);
await new Promise(queueMicrotask);
assert.equal(store.incidentSession.items.length, 101);
listeners.get("beforeunload")();
assert.equal(writes, baselineWrites + 1);
assert.ok(![...storage.values()].join("").includes("private"));
store.clearIncidents("qa");
assert.equal(store.incidentSession.items.length, 100);
console.log("Incident fixtures passed: redaction, persistence, bounds, deduplication, filters, 5000-event coalescing, batch ingestion, shutdown flush.");
